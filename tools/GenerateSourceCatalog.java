// Build helper only. Runtime source display is implemented in Bhash.
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

class GenerateSourceCatalog {
    static final Map<String,String> entries = new LinkedHashMap<>();
    static String read(String file) throws Exception {
        return Files.readString(Path.of(file), StandardCharsets.UTF_8).replace("\r\n", "\n");
    }
    static void methods(String key, String file, String... names) throws Exception {
        String source = read(file);
        StringBuilder result = new StringBuilder();
        Set<String> missing = new HashSet<>(List.of(names));
        Matcher m = Pattern.compile("(?m)^    (?:निजी|सार्वजनिक) (?:साझा )?फलन ([^\\s(]+)\\(").matcher(source);
        while (m.find()) {
            if (!List.of(names).contains(m.group(1))) continue;
            missing.remove(m.group(1));
            int end = methodEnd(source, source.indexOf('{', m.end()));
            long line = source.substring(0,m.start()).chars().filter(c -> c=='\n').count()+1;
            result.append("// ").append(file).append(":").append(line).append("\n")
                  .append(source, m.start(), end).append("\n\n");
        }
        if (!missing.isEmpty()) throw new IllegalStateException("Missing methods: " + file + " " + missing);
        entries.put(key, result.toString());
    }
    static int methodEnd(String s, int start) {
        int depth=0; boolean string=false, escape=false, comment=false;
        for(int i=start; i<s.length(); i++) {
            char c=s.charAt(i);
            if(comment) { if(c=='\n') comment=false; continue; }
            if(string) { if(escape) escape=false; else if(c=='\\') escape=true; else if(c=='"') string=false; continue; }
            if(c=='/' && i+1<s.length() && s.charAt(i+1)=='/') { comment=true; i++; continue; }
            if(c=='"') { string=true; continue; }
            if(c=='{') depth++;
            if(c=='}' && --depth==0) return i+1;
        }
        throw new IllegalStateException("Unclosed method");
    }
    static String literal(String s) {
        return "\""+s.replace("\\","\\\\").replace("\"","\\\"").replace("\n","\\n").replace("\t","\\t").replace("\r","\\r")+"\"";
    }
    public static void main(String[] args) throws Exception {
        String web="src/web.bhash", db="src/storage.bhash";
        methods("ui:signin",web,"प्रवेशपृष्ठ");
        methods("ui:organizations",web,"संगठनपृष्ठ");
        methods("ui:overview",web,"अवलोकन","राशि");
        methods("ui:list",web,"सूचीपृष्ठ","पृष्ठअंतर","राशि");
        methods("ui:record",web,"संपादन","राशि");
        methods("ui:members",web,"सदस्यपृष्ठ");
        methods("ui:audit",web,"लेखापृष्ठ","पृष्ठअंतर");
        methods("ui:account",web,"खातापृष्ठ");
        methods("ui:signup",web,"पंजीकरणपृष्ठ","पंजीकरणसूचना");
        methods("ui:verify",web,"ईमेलपुष्टिपृष्ठ");
        methods("ui:forgot",web,"कूटअनुरोधपृष्ठ","कूटसूचनापृष्ठ");
        methods("ui:reset",web,"कूटबदलपृष्ठ","कूटसफलपृष्ठ");
        methods("backend:forgot","src/signup.bhash","कूटअनुरोध","सीमा","ईमेलजाँचो");
        methods("backend:reset","src/signup.bhash","कूटविवरण","कूटपूरा");
        methods("backend:signup","src/signup.bhash","अनुरोध","कैप्चाजाँचो","सीमा","ईमेलजाँचो");
        methods("backend:verify","src/signup.bhash","पूरा","विवरण");
        methods("ui:layout",web,"शीर्षक","पथ","क्षेत्र","चुनो","भाषाफॉर्म","ढाँचा");
        methods("backend:signin",db,"खातानाम","प्रवेश");
        methods("backend:organizations",db,"संगठनसूची","नयासंगठन","संगठनबनाओ");
        methods("backend:overview",db,"सूचीलो","संगठननाम","संदर्भ","पंक्तिलो");
        methods("backend:list",db,"सूचीलो","संगठननाम","संदर्भ","पंक्तिलो");
        methods("backend:record",db,"पाओ","पंक्तिलो","सहेजो","संग्रहकरो");
        methods("backend:members",db,"सदस्यसूची","सदस्यबदलो","खातानाम","खाताबनाओ","कूटजाँचो","उपयोगकर्तालो");
        methods("backend:audit",db,"लेखासूची");
        methods("backend:account",db,"खाताविवरण","डिफ़ॉल्टभाषालो","भाषाबदलो","सत्रभाषारखो","कूटबदलो","जीवितखाता","भाषाजाँचो");
        methods("backend:validation",web,"रिकॉर्डलो","वैकल्पिक");
        methods("backend:routing",web,"संभालो");
        // Explicit public-source allowlist. Never scan runtime files or configuration.
        for(String file:List.of("src/main.bhash","src/errors.bhash","src/schema.bhash",
                "src/translations.bhash","src/source_viewer.bhash","src/signup.bhash",
                "packages/web-platform/src/source.bhash","packages/web-platform/src/ui.bhash","packages/web-platform/src/forms.bhash",
                "packages/web-platform/src/sessions.bhash","packages/web-platform/src/tenancy.bhash"))
            entries.put("file:"+file,read(file));
        StringBuilder out=new StringBuilder("// Generated by tools/GenerateSourceCatalog.java. Do not edit.\n// Only allowlisted Bhash source; no database, environment, credentials, or runtime files.\nवर्ग स्रोतसंग्रह {\n    सार्वजनिक साझा फलन लो(कुंजी: पाठ) -> पाठ {\n");
        int index=0;
        for(String key:entries.keySet()) out.append("        यदि (कुंजी==").append(literal(key)).append(") { लौटाओ स्रोतसंग्रह.भाग").append(index++).append("(); }\n");
        out.append("        फेंको नया अपवाद(\"अज्ञात स्रोत खंड।\");\n    }\n");
        index=0;
        List<String> chunks=new ArrayList<>();
        for(String value:entries.values()) {
            out.append("    निजी साझा फलन भाग").append(index++).append("() -> पाठ {\n        मान पाठांश: पाठ=\"\";\n");
            for(int start=0;start<value.length();) {
                int end=Math.min(start+1800,value.length());
                if(end<value.length() && Character.isHighSurrogate(value.charAt(end-1))) end--;
                out.append("        पाठांश=पाठांश+स्रोतसंग्रह.अंश").append(chunks.size()).append("();\n");
                chunks.add(value.substring(start,end));start=end;
            }
            out.append("        लौटाओ पाठांश;\n    }\n");
        }
        for(int chunk=0;chunk<chunks.size();chunk++)
            out.append("    निजी साझा फलन अंश").append(chunk).append("() -> पाठ { लौटाओ ").append(literal(chunks.get(chunk))).append("; }\n");
        out.append("}\n");
        Path output=Path.of("src/source_catalog.bhash");
        if(args.length>0 && args[0].equals("--check")) {
            if(!Files.exists(output) || !read(output.toString()).equals(out.toString()))
                throw new IllegalStateException("Source catalog is stale; run java tools/GenerateSourceCatalog.java");
        } else Files.writeString(output,out.toString(),StandardCharsets.UTF_8);
        System.out.println("Source catalog verified: "+entries.size()+" allowlisted sections.");
    }
}
